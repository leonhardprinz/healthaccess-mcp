#!/usr/bin/env python3
"""Generate HealthAccess/Services/HealthTypes.swift from the SDK's HKTypeIdentifiers.h.

Ground truth is the header of the SDK Xcode builds against, enumerated by regex, never a list from memory
(docs/export-coverage.md, "Rule going forward"). Every quantity, category, characteristic and correlation
identifier is emitted with its iOS availability, the unit and aggregation style from the header comment, and
the category value enum. Deprecated identifiers are skipped. Re-run after every Xcode update:

    cd app && python3 scripts/gen_health_types.py            # uses `xcrun --sdk iphoneos`
    python3 scripts/gen_health_types.py /path/to/HKTypeIdentifiers.h
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "HealthAccess", "Services", "HealthTypes.swift")

LINE = re.compile(
    r"HK_EXTERN HK(Quantity|Category|Characteristic|Correlation)TypeIdentifier const (HK\w+)\s+"
    r"(API_AVAILABLE|API_DEPRECATED\w*|API_UNAVAILABLE)\(([^;]*)\);\s*(?://\s*(.*))?"
)


def sdk_path():
    return subprocess.check_output(["xcrun", "--sdk", "iphoneos", "--show-sdk-path"], text=True).strip()


def sdk_version():
    try:
        return subprocess.check_output(["xcrun", "--sdk", "iphoneos", "--show-sdk-version"], text=True).strip()
    except Exception:
        return "unknown"


def parse(path):
    specs = {"Quantity": [], "Category": [], "Characteristic": [], "Correlation": []}
    skipped = []
    with open(path, encoding="utf-8") as f:
        for raw in f:
            m = LINE.search(raw)
            if not m:
                continue
            kind, ident, macro, args, comment = m.groups()
            if macro != "API_AVAILABLE":
                skipped.append(ident)
                continue
            ios = re.search(r"ios\(([0-9.]+)\)", args)
            ios = ios.group(1) if ios else "8.0"
            comment = (comment or "").strip()
            unit, agg, value_type = "", "", ""
            if kind == "Quantity":
                parts = [p.strip() for p in comment.split(",", 1)]
                unit = parts[0] if parts else ""
                agg = parts[1] if len(parts) > 1 else ""
            elif kind == "Category":
                value_type = comment
            specs[kind].append((ident, ios, unit, agg, value_type))
    return specs, skipped


def swift_literal(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def emit(specs, skipped, header_path, version):
    lines = []
    lines.append("// Generated by scripts/gen_health_types.py from HKTypeIdentifiers.h of the iOS %s SDK. Do not edit by hand." % version)
    lines.append("// Every HealthKit type identifier the SDK knows, with iOS availability, the unit and aggregation style of the")
    lines.append("// header comment, and the category value enum. The app requests read access to all of it and catalogs what has data.")
    lines.append("import Foundation")
    lines.append("")
    lines.append("struct HealthTypeSpec: Sendable, Hashable {")
    lines.append("    enum Kind: String, Sendable { case quantity, category, characteristic, correlation }")
    lines.append("    let identifier: String   // e.g. HKQuantityTypeIdentifierHeartRate")
    lines.append("    let kind: Kind")
    lines.append("    let ios: String          // first iOS version with this type")
    lines.append("    let unit: String         // header unit string for quantity types, e.g. \"count/min\"; \"\" otherwise")
    lines.append("    let aggregation: String  // \"Cumulative\", \"Discrete (Arithmetic)\", …; \"\" for non-quantity types")
    lines.append("    let valueType: String    // category value enum, e.g. \"HKCategoryValueSeverity\"; \"\" otherwise")
    lines.append("")
    lines.append("    /// The identifier without its prefix, e.g. \"HeartRate\".")
    lines.append("    var name: String {")
    lines.append("        let prefix: String")
    lines.append("        switch kind {")
    lines.append("        case .quantity: prefix = \"HKQuantityTypeIdentifier\"")
    lines.append("        case .category: prefix = \"HKCategoryTypeIdentifier\"")
    lines.append("        case .characteristic: prefix = \"HKCharacteristicTypeIdentifier\"")
    lines.append("        case .correlation: prefix = \"HKCorrelationTypeIdentifier\"")
    lines.append("        }")
    lines.append("        return identifier.hasPrefix(prefix) ? String(identifier.dropFirst(prefix.count)) : identifier")
    lines.append("    }")
    lines.append("")
    lines.append("    /// \"heart_rate_variability_sdnn\", \"vo2_max\": the key used in the files.")
    lines.append("    var key: String { HealthTypeSpec.snake(name) }")
    lines.append("")
    lines.append("    var isCumulative: Bool { aggregation.hasPrefix(\"Cumulative\") }")
    lines.append("")
    lines.append("    static func snake(_ s: String) -> String {")
    lines.append("        var out = \"\"")
    lines.append("        let chars = Array(s)")
    lines.append("        for (i, c) in chars.enumerated() {")
    lines.append("            if c.isUppercase {")
    lines.append("                if i > 0 {")
    lines.append("                    let prev = chars[i - 1]")
    lines.append("                    let nextIsLower = i + 1 < chars.count && chars[i + 1].isLowercase")
    lines.append("                    if prev.isLowercase || prev.isNumber || (prev.isUppercase && nextIsLower) { out.append(\"_\") }")
    lines.append("                }")
    lines.append("                out.append(contentsOf: c.lowercased())")
    lines.append("            } else {")
    lines.append("                out.append(c)")
    lines.append("            }")
    lines.append("        }")
    lines.append("        return out")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    lines.append("enum HealthTypes {")
    lines.append("    static let sdkVersion = %s" % swift_literal(version))
    lines.append("    static let headerFile = %s" % swift_literal(os.path.basename(header_path)))
    for kind, swift_kind in (("Quantity", "quantity"), ("Category", "category"), ("Characteristic", "characteristic"), ("Correlation", "correlation")):
        items = specs[kind]
        lines.append("")
        lines.append("    /// %d %s types." % (len(items), swift_kind))
        lines.append("    static let %s: [HealthTypeSpec] = [" % swift_kind)
        for ident, ios, unit, agg, value_type in items:
            lines.append("        HealthTypeSpec(identifier: %s, kind: .%s, ios: %s, unit: %s, aggregation: %s, valueType: %s),"
                         % (swift_literal(ident), swift_kind, swift_literal(ios), swift_literal(unit), swift_literal(agg), swift_literal(value_type)))
        lines.append("    ]")
    lines.append("")
    lines.append("    static var all: [HealthTypeSpec] { quantity + category + characteristic + correlation }")
    lines.append("")
    lines.append("    /// Identifiers the header marks deprecated; known, never requested.")
    lines.append("    static let deprecated: [String] = [%s]" % ", ".join(swift_literal(s) for s in skipped))
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    header = sys.argv[1] if len(sys.argv) > 1 else os.path.join(sdk_path(), "System/Library/Frameworks/HealthKit.framework/Headers/HKTypeIdentifiers.h")
    specs, skipped = parse(header)
    version = sdk_version() if len(sys.argv) < 2 else "custom"
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(emit(specs, skipped, header, version))
    print("wrote %s: %d quantity, %d category, %d characteristic, %d correlation; %d deprecated skipped" % (
        os.path.relpath(OUT, ROOT), len(specs["Quantity"]), len(specs["Category"]), len(specs["Characteristic"]), len(specs["Correlation"]), len(skipped)))


if __name__ == "__main__":
    sys.exit(main())
