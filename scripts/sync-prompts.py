#!/usr/bin/env python3
"""Copies docs/prompts.md (the source of truth) into its four copies:
app/HealthAccess/Services/Prompts.swift, the prompt articles of site/docs/prompts.html,
section 11 of site/llms-full.txt and the skills of the Claude plugin (claude-plugin/skills/). Run after every change to docs/prompts.md;
`--check` exits 1 when a copy is out of date (for CI)."""
import html, json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MD = (ROOT / "docs/prompts.md").read_text()
GROUPS = {"export": ("Export", "Understand what your Watch recorded"),
          "plans": ("Import", "Workout plans from your AI onto the Watch")}

def parse(md):
    out = []
    parts = re.split(r"^## (\d+)\. (.+)$", md, flags=re.M)
    for i in range(1, len(parts), 3):
        number, title, rest = int(parts[i]), parts[i + 1].strip(), parts[i + 2]
        lines = rest.strip("\n").split("\n")
        idline = lines[0]
        m = re.search(r"\*\*id:\*\* `([^`]+)`", idline)
        if not m:
            continue
        g = re.search(r"\*\*group:\*\* ([a-z]+)", idline)
        a = idline.split("**args:**", 1)[1].strip() if "**args:**" in idline else "none"
        rest_lines = lines[1:]
        about = ""
        if rest_lines and rest_lines[0].startswith("**about:**"):
            about = rest_lines[0][len("**about:**"):].strip()
            rest_lines = rest_lines[1:]
        body = "\n".join(rest_lines).strip()
        out.append(dict(number=number, id=m.group(1), title=title, group=g.group(1) if g else "export", about=about, args=a, body=body))
    return out

PROMPTS = parse(MD)
WORDS = {9: "Nine", 10: "Ten", 11: "Eleven", 12: "Twelve", 13: "Thirteen", 14: "Fourteen"}

def swift():
    def lit(s):
        return "\n".join(("        " + l) if l else "" for l in s.replace("\\", "\\\\").split("\n"))
    items = []
    for p in PROMPTS:
        items.append(
            f'        Prompt(id: "{p["id"]}", title: "{p["title"]}", group: .{p["group"]}, about: "{p["about"]}", args: "{p["args"]}", body: """\n'
            f'{lit(p["body"])}\n        """),')
    return f'''import Foundation

/// The prompts of docs/prompts.md, generated by scripts/sync-prompts.py. Do not edit by hand.
struct Prompt: Identifiable, Hashable {{
    enum Group: String, Hashable {{ case export, plans }}
    let id: String
    let title: String
    let group: Group
    let about: String
    let args: String
    let body: String
}}

enum Prompts {{
    static let all: [Prompt] = [
{chr(10).join(items)}
    ]

    static func `in`(_ group: Prompt.Group) -> [Prompt] {{ all.filter {{ $0.group == group }} }}
}}
'''

def inline(s):
    s = html.escape(s, quote=False)
    return re.sub(r"`([^`]+)`", r"<code>\1</code>", s)

def body_html(body):
    out = []
    for block in re.split(r"\n\s*\n", body.strip()):
        lines = block.split("\n")
        items = [l for l in lines if re.match(r"^\d+\. ", l)]
        lead = [l for l in lines if not re.match(r"^\d+\. ", l)]
        if lead:
            out.append(f"  <p>{inline(' '.join(lead))}</p>")
        if items:
            out.append("  <ol>")
            for l in items:
                text = inline(re.sub(r"^\d+\. ", "", l))
                out.append(f"    <li>{text}</li>")
            out.append("  </ol>")
    return "\n".join(out)

def site_articles():
    chunks = []
    for key, (name, sub) in GROUPS.items():
        chunks.append(f'<h2 id="{key}">{name}: {sub[0].lower() + sub[1:]}</h2>')
        for p in [p for p in PROMPTS if p["group"] == key]:
            args = "none" if p["args"] == "none" else inline(p["args"])
            chunks.append(f'''<article class="prompt-full" id="{p["id"]}">
  <h3>{p["number"]}. {html.escape(p["title"])}</h3>
  <p class="small">{inline(p["about"])}</p>
  <div class="meta">id: <code>{p["id"]}</code> · args: {args}</div>
  <div class="text">
{body_html(p["body"])}
  </div>
</article>''')
    return "\n\n".join(chunks)

def llms_section():
    n = len(PROMPTS)
    head = (f"## 11. Ideas for your AI: {n} prompts in two groups, suggestions only\n\n"
            "These are ideas, not a step of the setup: use them, change them or ignore them. What you share with an AI, and what it tells you, is between you and that AI. "
            "Every prompt asks before it reads data, and reads data before it writes anything. None assumes a sport. "
            "Export prompts read and explain; Plans prompts write sessions for the Watch. Voice: plain, short, no consultant words.\n")
    parts = [head]
    for key, (name, sub) in GROUPS.items():
        parts.append(f"\n{name} prompts ({sub[0].lower() + sub[1:]}):\n")
        for p in [p for p in PROMPTS if p["group"] == key]:
            parts.append(f"\n### {p['number']}. {p['title']}\nid: `{p['id']}` · group: {p['group']} · args: {p['args']}\nabout: {p['about']}\n\n{p['body']}\n")
    return "".join(parts) + "\n"

# When Claude should load each prompt as a plugin skill: the situations, in the athlete's words.
WHEN = {
    "weekly_checkin": "the athlete asks how their week went, wants a weekly review or a check-in",
    "explain_last_session": "the athlete asks about their last workout, a specific session, its laps or heart rate",
    "overdoing_it": "the athlete feels tired, flat or sore, asks whether they train too much or need rest",
    "sleep_and_recovery": "the athlete asks about sleep, recovery, resting heart rate, HRV or how rested they are",
    "long_term_trends": "the athlete asks what changed or improved over the last months or a quarter",
    "coach_summary": "the athlete wants a summary of their training or health data for a coach, doctor or physio",
    "next_session": "the athlete asks for their next workout, a session for today or tomorrow, or a Watch workout",
    "plan_my_week": "the athlete asks for a training week, a weekly plan or several sessions",
    "adjust_plans": "the athlete missed a session, is ill, tired or travelling, or wants to change planned workouts",
    "build_up_to_goal": "the athlete names a goal or event and a date (a race, a distance, a time to beat)",
    "convert_workout": "the athlete pastes or describes a workout from a coach, club, app or book to put on the Watch",
}

def skills():
    out = {}
    for p in PROMPTS:
        name = p["id"].replace("_", "-")
        about = p["about"].rstrip(".")
        desc = f"{about}. Use when {WHEN[p['id']]}. Needs the Health Access MCP server."
        args = "" if p["args"] == "none" else f"Arguments the athlete may give: {p['args']}.\n\n"
        out[f"claude-plugin/skills/{name}/SKILL.md"] = (
            f"---\nname: {name}\ndescription: {json.dumps(desc)}\n---\n\n"
            f"<!-- Generated from docs/prompts.md by scripts/sync-prompts.py. Do not edit by hand. -->\n\n"
            f"# {p['title']}\n\n{args}{p['body']}\n")
    return out

def apply(path, new_text, check):
    path = ROOT / path
    old = path.read_text() if path.exists() else None
    if old == new_text:
        return False
    if check:
        print(f"out of date: {path.relative_to(ROOT)}")
        return True
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(new_text)
    print(f"wrote {path.relative_to(ROOT)}")
    return True

def main():
    check = "--check" in sys.argv
    changed = apply("app/HealthAccess/Services/Prompts.swift", swift(), check)
    page = (ROOT / "site/docs/prompts.html").read_text()
    start = page.index('<article class="prompt-full"')
    start = page.rfind("\n", 0, start) + 1
    # an earlier run's group heading sits right before the first article
    prev = page.rfind('<h2 id="export">', 0, start)
    if prev != -1 and page[prev:start].count("<article") == 0:
        start = prev
    end = page.rindex("</article>") + len("</article>")
    n = WORDS.get(len(PROMPTS), str(len(PROMPTS)))
    page2 = page[:start] + site_articles() + page[end:]
    page2 = re.sub(r'<p class="answer">[^<]*?prompts(?: in two groups)?, suggestions only\.', f'<p class="answer">{n} prompts in two groups, suggestions only.', page2, count=1)
    changed |= apply("site/docs/prompts.html", page2, check)
    llms = (ROOT / "site/llms-full.txt").read_text()
    a = llms.index("## 11. Ideas for your AI")
    b = llms.index("## 12. ")
    changed |= apply("site/llms-full.txt", llms[:a] + llms_section() + llms[b:], check)
    generated = skills()
    for path, text in generated.items():
        changed |= apply(path, text, check)
    for old in sorted((ROOT / "claude-plugin/skills").glob("*/SKILL.md")):
        rel = str(old.relative_to(ROOT))
        if rel not in generated:
            changed = True
            if check:
                print(f"stale: {rel}")
            else:
                old.unlink(); old.parent.rmdir(); print(f"removed {rel}")
    if check and changed:
        sys.exit(1)

main()
