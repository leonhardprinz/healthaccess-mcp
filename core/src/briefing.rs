//! `briefing.md`: the one-page summary any AI can read without the MCP. The iOS app
//! writes it after every sync (contract: `docs/schema.md`, section "briefing.md").
//! When the folder has none yet, [`Store::generate_briefing`] builds the same
//! sections from `index.json`, the workout files, `vitals/` and `plans/`, and says
//! so in its first line.

use std::path::PathBuf;

use chrono::{DateTime, Duration, NaiveDate, Utc};
use serde::Serialize;

use crate::derive::effort_text;
use crate::model::workout::activity_label;
use crate::model::Vitals;
use crate::store::Store;
use crate::util::{fmt_duration, read_to_string, round_to};
use crate::Result;

/// Fixed sentence one of the "Limits" section.
pub const LIMIT_UNLOCK: &str = "Health data can only be read while the phone is unlocked, \
so a workout finished with the phone in the bag exports on the next unlock, not before.";
/// Fixed sentence two of the "Limits" section.
pub const LIMIT_POOL: &str = "The Watch keeps its own pool length setting; the plan cannot set it.";

/// Where a briefing came from.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum BriefingSource {
    /// `briefing.md` as the app wrote it.
    File,
    /// Built on the fly from the folder.
    Generated,
}

/// A briefing and where it came from.
#[derive(Debug, Clone, Serialize)]
pub struct Briefing {
    pub source: BriefingSource,
    pub text: String,
}

/// `1100 m` below 10 km, else `15.9 km`.
fn fmt_distance(m: f64) -> String {
    if m >= 10_000.0 {
        format!("{} km", round_to(m / 1000.0, 1))
    } else {
        format!("{} m", round_to(m, 0))
    }
}

/// Sleep as `7:25 h`.
fn fmt_hours(secs: f64) -> String {
    let minutes = secs.round().max(0.0) as u64 / 60;
    format!("{}:{:02} h", minutes / 60, minutes % 60)
}

fn mean(values: &[f64]) -> Option<f64> {
    (!values.is_empty()).then(|| values.iter().sum::<f64>() / values.len() as f64)
}

/// Direction of a metric over the window: the mean of the last 7 days against the
/// mean of the days before, with a tolerance band that reads as `flat`.
fn direction(points: &[(NaiveDate, f64)], today: NaiveDate, tolerance: f64) -> &'static str {
    let cut = today - Duration::days(7);
    let recent: Vec<f64> = points
        .iter()
        .filter(|(d, _)| *d > cut)
        .map(|(_, v)| *v)
        .collect();
    let earlier: Vec<f64> = points
        .iter()
        .filter(|(d, _)| *d <= cut)
        .map(|(_, v)| *v)
        .collect();
    match (mean(&recent), mean(&earlier)) {
        (Some(r), Some(e)) if r - e > tolerance => "up",
        (Some(r), Some(e)) if e - r > tolerance => "down",
        (Some(_), Some(_)) => "flat",
        _ => "too few days to tell",
    }
}

/// One "Vitals" line: latest value with its date and the 21-day direction.
fn vitals_line(
    label: &str,
    vitals: &[Vitals],
    pick: impl Fn(&Vitals) -> Option<f64>,
    show: impl Fn(f64) -> String,
    tolerance: f64,
    today: NaiveDate,
) -> String {
    let points: Vec<(NaiveDate, f64)> = vitals
        .iter()
        .filter_map(|v| pick(v).map(|x| (v.date, x)))
        .collect();
    match points.last() {
        None => format!("- {label}: no data"),
        Some((date, value)) => format!(
            "- {label} {} ({date}), 21 days: {}",
            show(*value),
            direction(&points, today, tolerance)
        ),
    }
}

impl Store {
    /// `briefing.md` in the folder.
    pub fn briefing_path(&self) -> PathBuf {
        self.dir().join("briefing.md")
    }

    /// The app's `briefing.md`, when it exists.
    pub fn briefing_file(&self) -> Result<Option<String>> {
        let path = self.briefing_path();
        if !path.is_file() {
            return Ok(None);
        }
        read_to_string(&path).map(Some)
    }

    /// The app's `briefing.md` when present, else one generated now.
    pub fn briefing(&self) -> Result<Briefing> {
        if let Some(text) = self.briefing_file()? {
            return Ok(Briefing {
                source: BriefingSource::File,
                text,
            });
        }
        Ok(Briefing {
            source: BriefingSource::Generated,
            text: self.generate_briefing(Utc::now())?,
        })
    }

    /// Build a briefing from the folder with the contract's section order: last 4
    /// weeks, recent sessions, vitals, next session, open items, limits. The first
    /// line says that the MCP generated it, not the app.
    pub fn generate_briefing(&self, now: DateTime<Utc>) -> Result<String> {
        let today = now.date_naive();
        let mut out: Vec<String> = Vec::with_capacity(48);
        out.push(format!(
            "# Health Access briefing for the athlete, written {} by healthaccess-mcp \
             (generated by the MCP from the folder, not by the app: there is no briefing.md yet)",
            now.format("%Y-%m-%dT%H:%MZ")
        ));

        // Last 4 weeks
        out.push(String::new());
        out.push("## Last 4 weeks".to_string());
        let summary = self.training_summary_at(4, today)?;
        for week in &summary.weeks {
            if week.sessions == 0 {
                out.push(format!(
                    "- {} ({} to {}): no sessions",
                    week.week, week.start, week.end
                ));
                continue;
            }
            let effort = match week.mean_effort {
                Some(e) => format!(
                    "mean effort {e} ({} of {} rated)",
                    week.rated_sessions, week.sessions
                ),
                None => "no effort ratings".to_string(),
            };
            out.push(format!(
                "- {} ({} to {}): {} session{}, {}, {}, {}",
                week.week,
                week.start,
                week.end,
                week.sessions,
                if week.sessions == 1 { "" } else { "s" },
                fmt_distance(week.distance_m),
                fmt_duration(week.duration_s),
                effort
            ));
        }

        // Recent sessions
        out.push(String::new());
        out.push("## Recent sessions".to_string());
        let index = self.index()?;
        if index.workouts.is_empty() {
            out.push("- none yet".to_string());
        }
        for entry in index.workouts.iter().take(10) {
            let loaded = self
                .load_workout_file(&self.workout_path(entry))
                .map(|mut w| {
                    self.enrich_with_plan(&mut w);
                    w
                });
            let (name, distance, duration, avg_hr, effort) = match &loaded {
                Ok(w) => (
                    match w.plan_ref.as_ref().and_then(|p| p.name.as_deref()) {
                        Some(n) => format!("{} \"{n}\"", activity_label(&w.activity)),
                        None => activity_label(&w.activity),
                    },
                    w.distance_m,
                    w.duration_s,
                    w.avg_hr,
                    effort_text(w.effort, w.effort_source.as_deref()),
                ),
                Err(_) => (
                    match &entry.plan_name {
                        Some(n) => format!("{} \"{n}\"", activity_label(&entry.activity)),
                        None => activity_label(&entry.activity),
                    },
                    entry.distance_m,
                    entry.duration_s,
                    entry.avg_hr,
                    effort_text(entry.effort, entry.effort_source.as_deref()),
                ),
            };
            let mut parts = vec![fmt_duration(duration)];
            if let Some(d) = distance.filter(|d| *d > 0.0) {
                parts.insert(0, fmt_distance(d));
            }
            parts.push(match avg_hr {
                Some(hr) => format!("avg HR {}", hr.round()),
                None => "no HR".to_string(),
            });
            parts.push(effort);
            out.push(format!(
                "- {} {name}: {}",
                entry.start.format("%Y-%m-%d"),
                parts.join(", ")
            ));
        }

        // Vitals
        out.push(String::new());
        out.push("## Vitals".to_string());
        let vitals = self.vitals_at(21, today)?;
        if vitals.is_empty() {
            out.push(
                "- none yet (the app writes a vitals file per day once it has Health access)"
                    .to_string(),
            );
        } else {
            out.push(vitals_line(
                "Resting HR",
                &vitals,
                |v| v.resting_hr,
                |x| format!("{} bpm", x.round()),
                2.0,
                today,
            ));
            out.push(vitals_line(
                "HRV",
                &vitals,
                |v| v.hrv_sdnn_ms,
                |x| format!("{} ms", round_to(x, 1)),
                5.0,
                today,
            ));
            out.push(vitals_line(
                "Sleep",
                &vitals,
                |v| v.sleep_s,
                fmt_hours,
                1200.0,
                today,
            ));
            out.push(vitals_line(
                "Weight",
                &vitals,
                |v| v.body_mass_kg,
                |x| format!("{} kg", round_to(x, 1)),
                0.5,
                today,
            ));
        }

        // Next session
        out.push(String::new());
        out.push("## Next session".to_string());
        let plans = self.list_plans()?;
        let next = plans
            .iter()
            .find(|p| p.state != "scheduled" && p.state != "cancelled");
        match next {
            None => out.push("- none".to_string()),
            Some(p) => {
                let mut bits = vec![format!(
                    "{} m planned, {} of timed steps",
                    p.planned_distance_m.round(),
                    fmt_duration(p.planned_time_s)
                )];
                bits.push(match p.scheduled_for {
                    Some(t) => format!("scheduled for {}", t.format("%Y-%m-%d %H:%MZ")),
                    None => "no date".to_string(),
                });
                bits.push(match p.state.as_str() {
                    "failed" => format!(
                        "failed on the phone: {}",
                        p.status
                            .as_ref()
                            .and_then(|s| s.error.clone())
                            .unwrap_or_else(|| "no error text".to_string())
                    ),
                    _ => "waiting for Put on Watch".to_string(),
                });
                out.push(format!(
                    "- {} ({}): {}",
                    p.name,
                    activity_label(&p.sport),
                    bits.join(", ")
                ));
            }
        }

        // Open
        out.push(String::new());
        out.push("## Open".to_string());
        let unrated: Vec<_> = index
            .workouts
            .iter()
            .filter(|e| e.effort.is_none())
            .collect();
        let waiting: Vec<&str> = plans
            .iter()
            .filter(|p| p.state == "pending")
            .map(|p| p.name.as_str())
            .collect();
        if unrated.is_empty() && waiting.is_empty() {
            out.push("- nothing".to_string());
        }
        if let Some(newest) = unrated.first() {
            out.push(format!(
                "- {} session{} without an effort rating, newest {} {} ({})",
                unrated.len(),
                if unrated.len() == 1 { "" } else { "s" },
                newest.start.format("%Y-%m-%d"),
                activity_label(&newest.activity),
                newest.short_id()
            ));
        }
        if !waiting.is_empty() {
            out.push(format!(
                "- {} plan{} waiting for Put on Watch: {}",
                waiting.len(),
                if waiting.len() == 1 { "" } else { "s" },
                waiting.join(", ")
            ));
        }

        // Limits
        out.push(String::new());
        out.push("## Limits".to_string());
        out.push(LIMIT_UNLOCK.to_string());
        out.push(LIMIT_POOL.to_string());

        let mut text = out.join("\n");
        text.push('\n');
        Ok(text)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn d(s: &str) -> NaiveDate {
        s.parse().unwrap()
    }

    #[test]
    fn direction_compares_last_week_with_the_days_before() {
        let today = d("2026-10-25");
        let pts: Vec<(NaiveDate, f64)> = (0..21)
            .map(|i| {
                (
                    today - Duration::days(20 - i),
                    if i >= 14 { 65.0 } else { 60.0 },
                )
            })
            .collect();
        assert_eq!(direction(&pts, today, 2.0), "up");
        let flat: Vec<(NaiveDate, f64)> = pts.iter().map(|(dt, _)| (*dt, 60.0)).collect();
        assert_eq!(direction(&flat, today, 2.0), "flat");
        let down: Vec<(NaiveDate, f64)> = pts.iter().map(|(dt, v)| (*dt, 125.0 - v)).collect();
        assert_eq!(direction(&down, today, 2.0), "down");
        assert_eq!(direction(&pts[18..], today, 2.0), "too few days to tell");
    }

    #[test]
    fn distances_switch_to_km_at_ten() {
        assert_eq!(fmt_distance(1100.0), "1100 m");
        assert_eq!(fmt_distance(15_900.0), "15.9 km");
        assert_eq!(fmt_hours(25_200.0), "7:00 h");
        assert_eq!(fmt_hours(26_700.0), "7:25 h");
    }
}
